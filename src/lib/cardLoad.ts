/* ------------------------------------------------------------------ *
 * 名片表什么时候该重新拉
 *
 * 全 App 的头像共用一张名片表（store/useCards）。这个文件只回答一句话：
 * **现在该不该再去拉一次。**
 *
 * -------------------------------------------------------------------
 * 为什么值得单拎出来
 *
 * 这一判错了**不会报错**，表现是「头像不见了」—— 所有人的照片悄悄
 * 退回卡通角色，和「大家都没设过照片」长得一模一样。没有一行日志、
 * 没有一个红框，而人只会觉得这个 App 时好时坏。
 *
 * 原来那版是一个 `loaded` 布尔：
 *
 *     if (get().loaded && !force) return
 *     const cards = await fetchCards()
 *     set({ cards, loaded: true })
 *
 * 两个窟窿，都是「静悄悄地错」：
 *
 * **一、没登录时拉的那一张，一直当成数了。**
 *   名片表是按「谁在看」过滤的（自己 / 好友 / 同群）。登录前拉，
 *   数据库看到的是一个陌生人，回来的基本是空表 —— 然后 `loaded`
 *   立成 true。接着他登录了，**没有任何东西会再拉一次**，于是整个
 *   App 的头像全是卡通，直到他彻底关掉重开。
 *
 *   今天这一条踩得最狠：注册登录来回试了几趟，每退出再进来一次，
 *   头像就没了一次。
 *
 * **二、拉失败和「真的没有」分不开。**
 *   fetchCards 拉不到就回一张空表（那是对的，不该让一个锦上添花的
 *   东西把整屏搞崩）。但调用方把空表当成功记了账，于是地铁里开一次
 *   App，这一整次使用里头像就都没了。
 *
 * 下面这个函数把两件事都收口：**按「这张表是谁的」记账，而且只在
 * 成功时记。** 没成功过就一直是「该拉」，回前台那一下自然就是重试。
 * ------------------------------------------------------------------ */

/**
 * 现在该不该去拉名片表。
 *
 * 整条规矩就一句：**手上这张表要是不属于现在这个人，就去拉。**
 *
 * 一个比较同时管住三件事，这不是省代码，是让它们不可能各自跑偏：
 *
 *   没成功过   loadedFor 是 undefined，而 uid 只会是 string 或 null，
 *              永远不相等 —— 于是「一直该拉」。失败不记账，所以这
 *              顺带就是重试：问一次就试一次，不用定时器，也不空转
 *   换人了     登录、登出、换账号都算。这张表是按「谁在看」过滤的
 *              （自己 / 好友 / 同群），换了人内容就不对了。登出那一下
 *              也必须拉 —— 不拉的话，下一个在这台手机上登录的人，
 *              第一眼看到的是上一个人的头像
 *   已经是了   不花那个请求。这张表一小时也变不了一次，而「切回 App」
 *              一天能有几十次
 *
 * 原来还写成两段 if，第一段专门认 undefined。改坏源码跑测试才发现
 * 那一段**删掉行为一模一样** —— 它读起来像一条规矩，其实是条死代码，
 * 而死代码会让人以为那里有个把关的。
 */
export function shouldLoadCards(o: {
  /**
   * 上一次**拉成功**时登录的是谁。
   *
   *   undefined  从来没成功过
   *   null       登出状态下拉成功的
   *   string     这个账号拉成功的
   *
   * 「成功」和「登录的是谁」必须一起记：少了前者分不出失败，
   * 少了后者分不出换人。
   */
  loadedFor: string | null | undefined
  /** 现在登录的是谁，没登录是 null */
  uid: string | null
}): boolean {
  return o.loadedFor !== o.uid
}

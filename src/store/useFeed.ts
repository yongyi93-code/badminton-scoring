import { create } from 'zustand'

/* ------------------------------------------------------------------ *
 * 「刚才发了/删了一条」这个信号
 *
 * 一条动态到底落在哪一边，发的人在最后一刻还能改：那张纸上的
 * 「留多久」一改，本来要进那一排圈圈的就变成了普通动态，反过来也一样。
 *
 * 于是**谁发的谁刷新**这条规矩是不成立的 —— 从圈圈那个「＋」发出去的
 * 东西可能该出现在时间线上，而那一屏不知道发生过什么。表现出来是：
 * 发完看不见自己刚发的那条。那是最让人以为「没发出去」然后再发一遍
 * 的一种错，而再发一遍是真的会多出一条。
 *
 * 所以改成一个共用的号码牌：发了、删了就加一。谁关心谁盯着它。
 * ------------------------------------------------------------------ */

type State = {
  /** 变一次就说明「有人发了或删了一条」，值本身没有意义 */
  n: number
  bump: () => void
}

export const useFeed = create<State>((set) => ({
  n: 0,
  bump: () => set((s) => ({ n: s.n + 1 })),
}))

/** 在组件外面（回调里）叫一声用这个 */
export const feedChanged = () => useFeed.getState().bump()

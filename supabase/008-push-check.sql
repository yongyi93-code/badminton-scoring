-- ===================================================================
-- 开局提醒为什么没响
--
-- 只读。不改任何东西。
--
-- 推送要三方接力，缺一环就整条链路静悄悄地失效，而且哪一环断了
-- 在手机上看起来都一样（就是没收到）。这一句先回答最前面那一环：
-- 到底有没有人订过。
--
-- 「订过的设备」是 0 的话，后面两环再对也不会有人收到 —— 那时候
-- 该做的是让大家各自去「我的」里把开局提醒打开一次，
-- 而不是去查函数和密钥。
-- ===================================================================

select
  count(*)                                                as 订过的设备,
  count(distinct player_id) filter (where player_id is not null) as 订过的人,
  count(*) filter (where created_at > now() - interval '7 days')  as 最近七天新订的,
  min(created_at)                                         as 最早一条,
  max(created_at)                                         as 最新一条
from public.push_subscribers;
